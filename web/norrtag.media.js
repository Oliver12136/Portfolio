window.NorrtagMediaSources = (function () {
  function paintedWidth(media, entry) {
    var box = media.getBoundingClientRect();
    return Math.max(box.width, box.height * entry.width / entry.height) || entry.width;
  }
  return {
    image: function (media, src) {
      var entry = window.NorrtagResponsiveImages[src];
      if (entry) {
        var sizes = Math.ceil(paintedWidth(media, entry)) + "px";
        var srcset = entry.sources.map(function (source) { return source.src + " " + source.width + "w"; }).join(", ");
        if (media.sizes !== sizes) media.sizes = sizes;
        if (media.getAttribute("srcset") !== srcset) media.srcset = srcset;
      }
      if (media.getAttribute("src") !== src) media.src = src;
    },
    poster: function (media, src) {
      var entry = window.NorrtagResponsiveImages[src];
      if (!entry) return src;
      var target = paintedWidth(media, entry) * (window.devicePixelRatio || 1);
      return (entry.sources.find(function (source) { return source.width >= target; }) || entry.sources[entry.sources.length - 1]).src;
    }
  };
})();
